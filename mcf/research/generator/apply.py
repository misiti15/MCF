def run(date: str, n: int = 10, apply: bool = False, n_specs: int = 3000, seed: int | None = None, workers: int = 3,
        screen_workers: int = 4, log=print, panel=None, seeds: bool = True, discovery=None, min_long: int = 5) -> dict:
    """seeds: add the weekly Setup lab scan's replicated rules (seeds.py) to the pool; discovery: a path to a
    discovery latest.json, or a loaded dict (default: origin/mcf-data:discovery/latest.json, fail soft)."""
    from . import data as D
    from . import seeds as SD

    t0 = time.time()
    seed = int(date.replace("-", "")) if seed is None else seed
    P = panel if panel is not None else D.load(workers=workers, log=log)
    log(f"panel: {P.n} rows, {P.n_days} sessions ({time.time() - t0:.0f}s)")
    qtab = S.quantile_table(P, seed=seed)
    acct = load_account()
    prior = {k: spec_from_cfg(v) for k, v in acct["strategies"].items() if k.startswith("GEN-")}
    prior = {k: s for k, s in prior.items() if s is not None}
    avoid = S.tried_families() | {s.family() for s in prior.values()}
    seen = registry_keys() | {s.key() for s in prior.values()}
    # Setup lab seeds (owner 2026-10-19): same screen, ranking and pick rules as random specs; counted in n_tried
    seed_specs, seed_info, seed_meta = [], None, {}
    if seeds:
        disc = discovery if isinstance(discovery, dict) else SD.load_discovery(discovery, log=log)
        seed_specs, seed_info, seed_meta = SD.generate(disc, seen, avoid, log=log)
    specs, rej = S.generate(qtab, n_specs, seed, seen | set(seed_meta), avoid, log=log)
    log(f"generated {len(specs)} specs (rejected: {rej}); {len(avoid)} prior families avoided")
    specs = seed_specs + specs
    res = S.screen(P, specs, workers=screen_workers, log=log)
    ranked = S.rank(res)
    by_key = {s.key(): s for s in specs}
    log(f"scored {len(res)} ({len(ranked)} rankable, {sum(r['tier1'] for r in ranked)} tier 1) ({time.time() - t0:.0f}s)")
    existing, not_checked = S.existing_keys(P, SAMPLE_MONTHS, log=log)
    sample_days = {d for d in P.days if d[:7] in SAMPLE_MONTHS}
    sd_first = np.r_[True, P.sd[1:] != P.sd[:-1]]
    months_mask = np.zeros(int(P.sd.max()) + 1, bool)
    months_mask[P.sd[sd_first]] = np.isin(P.days[P.day[sd_first]], list(sample_days))
    prior_eval = {k: S.evaluate(P, s, keep_keys=True) for k, s in prior.items()}
    prior_keys = {k: v["_keys"] for k, v in prior_eval.items()}
    picks = S.pick(P, by_key, ranked, n, existing, prior_keys, months_mask=months_mask, log=log, min_long=min_long)
    out = []
    for i, p in enumerate(picks, start=1 + sum(1 for k in prior if k.startswith(f"GEN-{date.replace('-', '')[2:]}-"))):
        s = by_key[p["key"]]
        nm = setup_name(s, date, i)
        stats = {k: v for k, v in p.items() if not k.startswith("_") and k != "name_tmp"}
        stats["date"] = date
        if stats.get("overlap_with") == p["key"]:
            stats["overlap_with"] = None
        if p["key"] in seed_meta:
            stats["seed"] = seed_meta[p["key"]]
        stats["expected_live_per_day"] = E.expected_live_per_day(stats.get("per_day_median60"))   # GX5
        out.append({"name": nm, "module": f"research/generator/modules/{module_slug(s, date, i)}.py", "spec": s.canon(),
                    "display": display_name(s), "what": what(s), "screen": stats})
    finalists = []
    for r in ranked[:50]:
        s = by_key[r["key"]]
        finalists.append({"key": r["key"], "spec": s.canon(), "train": r["train"], "valid": r["valid"],
                          "per_day": r["per_day"], "exp_up": r["exp_up"], "exp_down": r["exp_down"], "score": r["score"],
                          "tier1": r["tier1"], "skipped_overlap": r.get("skipped_overlap"),
                          "seed": r["key"] in seed_meta})
    if seed_info is not None:
        seed_info["screened"] = sum(1 for r in res if r["key"] in seed_meta)
        seed_info["ranked"] = sum(1 for r in ranked if r["key"] in seed_meta)
        seed_info["tier1"] = sum(1 for r in ranked if r["key"] in seed_meta and r["tier1"])
        seed_info["picked"] = sum(1 for p in out if p["screen"].get("seed"))
    rep = {"date": date, "seed": seed, "n_tried": len(res), "n_scored": len(ranked),
           "n_tier1": int(sum(r["tier1"] for r in ranked)), "rejected_before_screen": rej,
           "prior_families_avoided": len(avoid), "overlap_not_checked": not_checked,
           "overlap_sample_months": list(SAMPLE_MONTHS), "seeds": seed_info, "picks": out, "top50_finalists": finalists,
           # GX5 (owner 2026-10-26): every GEN setup's realistic live trades/day, refreshed on the full panel each run
           "expected_live": {**{k: E.entry(v) for k, v in sorted(prior_eval.items())},
                             **{x["name"]: E.entry(x["screen"]) for x in out}},
           "expected_live_basis": E.basis(),
           "applied": bool(apply), "runtime_s": round(time.time() - t0),
           "note": "Quick screen, open history only (train <= 2025-12, valid 2026-01..2026-10-07), costs in, "
                   "first qualifying bar per symbol-day, day-clustered t. No locked holdout; not a tested edge. "
                   f"{len(res)} configurations scored in this run. Educational only - not financial advice."}
    if apply:
        _apply(date, rep, specs, acct)
    return rep


def _apply(date: str, rep: dict, specs: list, acct: dict) -> None:
    MODULES.mkdir(parents=True, exist_ok=True)
    RUNS.mkdir(parents=True, exist_ok=True)
    names_y = NAMES_YAML.read_text()
    names_j = json.loads(NAMES_JSON.read_text())
    for p in rep["picks"]:
        s = Spec(p["spec"]["side"], p["spec"]["window"], p["spec"]["geom"], p["spec"]["min_adv"],
                 [tuple(c) for c in p["spec"]["conds"]])
        (ROOT / p["module"]).write_text(module_source(s, p["name"], p["screen"], rep["n_tried"]))
        sc = p["screen"]
        acct["strategies"][p["name"]] = {
            "enabled": True, "type": "lab", "module": p["module"],
            "context": sorted({c[0] for c in s.conds if c[0] in CONTEXT}),
            "min_adv": int(s.min_adv), "window": list(WINDOWS[s.window]), "refire": False, "scale_out_r": None,
            "tags": ["generated", f"gen-{date}"],
            "gen": {"date": date, "spec": s.canon(), "key": s.key(),
                    "screen": {"train": sc["train"], "valid": sc["valid"], "all": sc["all"], "per_day": sc["per_day"],
                               "per_day_valid": sc["per_day_valid"], "per_day_median60": sc.get("per_day_median60"),
                               "expected_live_per_day": sc.get("expected_live_per_day"), "exp_up": sc["exp_up"],
                               "exp_down": sc["exp_down"], "exp_flat": sc["exp_flat"],
                               "excess_train": sc["excess_train"], "excess_valid": sc["excess_valid"],
                               "tier1": sc["tier1"], "score": sc["score"], "max_overlap": sc["max_overlap"],
                               "overlap_with": sc["overlap_with"], "n_tried_in_run": rep["n_tried"]}},
        }
        if sc.get("seed"):
            acct["strategies"][p["name"]]["gen"]["seed"] = sc["seed"]
        entry = {"name": p["display"], "side": s.side, "what": p["what"], "generated": date,
                 "screen": {"train_exp_r": sc["train"]["exp_r"], "valid_exp_r": sc["valid"]["exp_r"],
                            "per_day": sc["per_day"], "expected_live_per_day": sc.get("expected_live_per_day")}}
        names_j[p["name"]] = entry
        names_y += (f"{p['name']}:\n  name: {json.dumps(p['display'])}\n  side: {s.side}\n"
                    f"  what: {json.dumps(p['what'])}\n  generated: \"{date}\"\n")
    write_account(acct)
    NAMES_YAML.write_text(names_y)
    NAMES_JSON.write_text(json.dumps(names_j, indent=1) + "\n")
    (RUNS / f"{date}.json").write_text(json.dumps(rep, indent=1, default=str) + "\n")
    with REGISTRY.open("a") as f:
        picked = {p["spec"] and Spec(p["spec"]["side"], p["spec"]["window"], p["spec"]["geom"], p["spec"]["min_adv"],
                                     [tuple(c) for c in p["spec"]["conds"]]).key(): p["name"] for p in rep["picks"]}
        for s in specs:
            k = s.key()
            rec = {"k": k, "d": date}
            if k in picked:
                rec.update({"name": picked[k], "spec": s.canon(), "fam": s.family()})
            f.write(json.dumps(rec, separators=(",", ":")) + "\n")
    pos = [p for p in rep["picks"] if (p["screen"]["train"]["exp_r"] or -1) > 0 and (p["screen"]["valid"]["exp_r"] or -1) > 0]
    led = {"id": f"{date}-gen-seed" if not any(l.startswith(f'{{"id": "{date}-gen') for l in LEDGER.read_text().splitlines()) else f"{date}-gen-{int(time.time())}",
           "date": date,
           "title": f"Setup Generator: {len(rep['picks'])} machine-generated GEN setups for the Setup Generator paper account (exploration; no promotion rules)",
           "patch": {}, "evidence": ["config/account_gen.yaml", f"research/generator/runs/{date}.json",
                                     "research/generator/registry.jsonl", "mcf/research/generator/"]
           + [p["module"] for p in rep["picks"]],
           "metrics_at_approval": {"configs_scored": rep["n_tried"], "tier1": rep["n_tier1"], "picked": len(rep["picks"]),
                                   "picked_positive_train_and_valid": len(pos)},
           "approved_by": "owner 2026-10-19 (Setup Generator account: 10 new GEN setups per day, no promotion rules)",
           "notes": "Gen account only (strategies_exclusive); primary / Testing 1 / Testing 2 / long-hold unchanged. Quick screen "
                    "on the open history, costs in, locked block never read; screen stats (negative ones too) in each setup's gen.screen.",
           "effective": date, "kind": "trading",
           "plain": f"The Setup Generator account gets {len(rep['picks'])} new machine-generated setups to try out on paper.",
           "impact": "Setup Generator account only: new GEN-* setups trade from the next run; see the Generated setups leaderboard."}
    with LEDGER.open("a") as f:
        f.write(json.dumps(led) + "\n")
    from .summary import write as write_summary   # Generator Lab card (owner 2026-10-19)
    write_summary(ROOT)
