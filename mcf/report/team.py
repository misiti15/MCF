def push(rep: dict, picks_file: str | None = None, workdir: Path | None = None, log=print) -> bool:
    """Publish team/<date>.json + team/latest.json (+ picks/latest.json, scoreboard.csv) to the mcf-data-team branch
    (raw URL read by the dashboard card). A data branch: no PR needed. Failures are logged, never fatal."""
    wd = Path(workdir or CACHE / "branch")

    def g(*a, cwd=wd):
        r = subprocess.run(["git", "-C", str(cwd), *a], capture_output=True, text=True)
        if r.returncode:
            log(f"git {' '.join(a[:2])}: {r.stderr.strip()[:200]}")
        return r.returncode == 0

    url = _git("remote", "get-url", "origin")
    if not url:
        log("push: no origin remote")
        return False
    if not (wd / ".git").exists():
        wd.mkdir(parents=True, exist_ok=True)
        g("init", "-q")
        g("remote", "add", "origin", url.strip())
    if g("fetch", "-q", "origin", BRANCH):
        g("checkout", "-q", "-B", BRANCH, f"origin/{BRANCH}")
    else:
        g("checkout", "-q", "--orphan", BRANCH)
    (wd / "team").mkdir(exist_ok=True)
    body = json.dumps(rep, indent=1, default=str)
    (wd / "team" / f"{rep['date']}.json").write_text(body)
    (wd / "team" / "latest.json").write_text(body)
    if picks_file:
        (wd / "picks").mkdir(exist_ok=True)
        shutil.copy(ROOT / picks_file, wd / "picks" / Path(picks_file).name)
        shutil.copy(ROOT / picks_file, wd / "picks" / "latest.json")
    sb = OUT / "scoreboard.csv"
    if sb.exists():
        shutil.copy(sb, wd / "scoreboard.csv")
    readme = wd / "README.md"
    if not readme.exists():
        readme.write_text("# mcf-data-team\n\nClaude's Team (shadow) data: team/<date>.json, team/latest.json, picks/, "
                          "scoreboard.csv, written by `python -m mcf.report.team --date D --push`. See "
                          "research/shadow_primary/README.md on the main branch. Shadow — simulated independently; no orders. "
                          f"{DISCLAIMER}\n")
    g("add", "-A")
    if subprocess.run(["git", "-C", str(wd), "diff", "--cached", "--quiet"]).returncode == 0:
        log("push: nothing new")
        return True
    g("-c", "user.name=mcf-bot", "-c", "user.email=mcf-bot@users.noreply.github.com", "commit", "-q", "-m",
      f"team {rep['date']} {rep['phase']} {rep.get('asof') or ''}".strip())
    for _ in range(3):
        if g("push", "-q", "origin", f"HEAD:{BRANCH}"):
            log(f"push: {BRANCH} team/{rep['date']}.json -> {RAW_URL}")
            return True
        g("-c", "user.name=mcf-bot", "-c", "user.email=mcf-bot@users.noreply.github.com", "pull", "-q", "--rebase",
          "origin", BRANCH)
    return False


def main(argv=None):
    ap = argparse.ArgumentParser(description="Claude's Team (shadow): independent simulated Primary book")
    ap.add_argument("--date", default=None, help="session date (default: today ET)")
    ap.add_argument("--now", default=None, help="pretend clock (ET), e.g. '2026-11-06 11:30' (tests / replays)")
    ap.add_argument("--label", default=None, help="e.g. 'backfill demo'")
    ap.add_argument("--push", action="store_true", help="publish to the mcf-data-team branch (dashboard card)")
    ap.add_argument("--no-scoreboard", action="store_true")
    ap.add_argument("--picks", default=None, help="explicit picks file (default: picks/<date>.json or the latest before)")
    a = ap.parse_args(argv)
    now = pd.Timestamp(a.now, tz=NY) if a.now else pd.Timestamp.now(tz=NY)
    day = a.date or str(now.date())
    rep = build(day, now=now, label=a.label, picks_file=a.picks)
    p = write(rep)
    if not a.no_scoreboard and rep["phase"] != "pre-open":
        append_scoreboard(rep)
    print(text(rep))
    print(f"wrote {p.relative_to(ROOT)}")
    if a.push:
        push(rep, picks_file=rep.get("picks_file"))


if __name__ == "__main__":
    main()
