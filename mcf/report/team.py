def get_priors(syms: list[str], day, exact: list[str], log=print) -> dict:
    """The live prep's priors (mcf.data.priors.build_priors, unchanged; read-only Alpaca market data), cached per day."""
    from ..data.priors import build_priors

    p = CACHE / "priors" / f"{pd.Timestamp(str(day)).date()}.pkl.gz"
    if p.exists():
        with gzip.open(p, "rb") as f:
            have = pickle.load(f)
        miss = [s for s in syms if s not in have.get("_asked", set())]
        if not miss:
            return {k: v for k, v in have.items() if k != "_asked"}
    log(f"team: building priors for {len(syms)} symbols (Alpaca market data, before {day})")
    pri = build_priors(list(syms), pd.Timestamp(str(day)).date(), feed="sip", exact_symbols=list(exact), log=log)
    p.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(p.with_suffix(".tmp"), "wb", compresslevel=3) as f:
        pickle.dump({**pri, "_asked": set(syms)}, f)
    p.with_suffix(".tmp").replace(p)
    return pri


def get_bars(syms: list[str], day, until: pd.Timestamp | None, log=print) -> dict[str, pd.DataFrame]:
    """symbol -> RTH 1-minute SIP bars of the session up to `until` (None = the whole session). Cached; an intraday cache
    is refetched when it ends before `until`."""
    from ..replay import store

    d = pd.Timestamp(str(day)).date()
    p = CACHE / "1Min" / f"{d}.parquet"
    end = (until or pd.Timestamp(f"{d} 16:00", tz=NY))
    meta = p.with_suffix(".json")
    ok = False
    if p.exists() and meta.exists():
        m = json.loads(meta.read_text())
        ok = pd.Timestamp(m["end"]) >= end and set(syms) <= set(m.get("asked", []))
    if not ok:
        log(f"team: fetching 1-minute bars for {len(syms)} symbols, {d} 09:30 -> {end:%H:%M} ET")
        df = store._fetch_bars(list(syms), pd.Timestamp(f"{d} 09:30", tz=NY).tz_convert("UTC").isoformat(),
                               end.tz_convert("UTC").isoformat(), "1Min")
        if len(df):
            df = df.set_index("ts")
            df.index = df.index.tz_convert(NY)
            df = df[(df.index.time >= pd.Timestamp("09:30").time()) & (df.index.time < pd.Timestamp("16:00").time())]
            df = df[df.index < end]
        p.parent.mkdir(parents=True, exist_ok=True)
        x = df.rename_axis("ts").reset_index() if len(df) else pd.DataFrame(columns=["symbol", "ts", "open", "high", "low", "close", "volume"])
        x.to_parquet(p, index=False)
        meta.write_text(json.dumps({"end": str(end), "asked": sorted(syms), "fetched_at": str(pd.Timestamp.now(tz=NY))}))
    x = pd.read_parquet(p)
    out = {}
    if len(x):
        ts = pd.DatetimeIndex(x["ts"]).tz_convert(NY)
        x = x.drop(columns="ts").set_index(ts)
        x = x[x.index < end]
        for sym, g in x.groupby("symbol", observed=True):
            out[str(sym)] = g[["open", "high", "low", "close", "volume"]].astype(float)
    return out


