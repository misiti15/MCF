# ------------------------------------------------------------------------------------------------------------- simulate
def _r(pnl, entry, stop, shares) -> float:
    risk = abs(float(entry) - float(stop)) * abs(float(shares))
    return float(pnl) / risk if risk > 0 else float("nan")


def mark_open(res: dict, until: pd.Timestamp) -> list[dict]:
    """Lots still open at `until` (an intraday run): marked at the last 1-minute close minus the exit cost."""
    from ..replay.broker import OPEN

    r, client = res["runner"], res["client"]
    if not client.pos:
        return []
    orders = r.journal.db.execute("SELECT broker_order_id, strategy, stop, qty, side FROM orders").fetchall() \
        if hasattr(r.journal, "db") else []
    meta = {str(o[0]): o for o in orders}
    k = client.mkt.minute(until)
    out = []
    for o in client.orders:
        if o._role != "entry" or o.status != "filled" or o.symbol not in client.pos:
            continue
        if not any(leg.status in OPEN for leg in (o.legs or [])):
            continue
        side = 1 if str(getattr(o.side, "value", o.side)) == "buy" else -1
        qty = min(abs(float(o.qty)), abs(client.pos[o.symbol]))
        fill = float(o.filled_avg_price)
        m = meta.get(str(o.id))
        stop0 = float(m[2]) if m and m[2] is not None else next(
            (float(leg.stop_price) for leg in (o.legs or []) if leg._role == "stop"), fill)
        last = client.mkt.last_close(o.symbol, k)
        if last is None:
            continue
        exit_px = client._cost(float(last), o.symbol, -side, "market")
        pnl = side * (exit_px - fill) * qty
        out.append({"symbol": o.symbol, "strategy": (m[1] if m else r.open_strategy.get(o.symbol)) or "?", "side": side,
                    "entry_time": str(pd.Timestamp(o.filled_at).tz_convert(NY)) if o.filled_at else None,
                    "entry": round(fill, 4), "stop": round(stop0, 4), "exit": round(exit_px, 4),
                    "exit_time": str(until), "exit_reason": "open (marked)", "shares": qty, "pnl": round(pnl, 2),
                    "r": round(_r(pnl, fill, stop0, qty), 4), "open": True})
    return out


def simulate(cfg: dict, day, bars: dict, priors: dict, until: pd.Timestamp | None, shortable: dict,
             spreads, log=print) -> dict:
    """One Team session through the as-live replay engine. Returns {trades, signals, stats}."""
    from ..replay import harness

    res = harness.run_session(cfg, day, bars, priors, fills="costs", limit_fill="through", spreads=spreads,
                              shortable=shortable, log=log, until=until, keep=True)
    tr = res["trades"]
    rows = []
    for t in tr.itertuples() if len(tr) else []:
        rows.append({"symbol": t.symbol, "strategy": t.strategy, "side": int(t.side),
                     "entry_time": str(pd.Timestamp(t.entry_time).tz_convert(NY)) if t.entry_time else None,
                     "entry": round(float(t.entry), 4), "stop": round(float(t.stop), 4),
                     "exit": None if pd.isna(t.exit) else round(float(t.exit), 4),
                     "exit_time": str(pd.Timestamp(t.exit_time).tz_convert(NY)) if t.exit_time else None,
                     "exit_reason": t.exit_reason, "shares": int(t.shares), "pnl": round(float(t.pnl), 2),
                     "r": round(_r(t.pnl, t.entry, t.stop, t.shares), 4), "open": False})
    if until is not None:
        rows += mark_open(res, until)
    sig = res["signals"]
    return {"trades": rows, "signals": sig, "stats": res["stats"]}


# ------------------------------------------------------------------------------------------------------------- actual
def actual_primary(day) -> dict:
    """Primary's actual session: journal R after costs (pnl_adj / risk, the live convention), journal P/L and the Alpaca
    day P/L (mcf.report.reconcile_pl; equity change vs the prior close)."""
    d = str(pd.Timestamp(str(day)).date())
    out = {"r": None, "trades": 0, "pnl_journal": None, "pnl_alpaca": None, "alpaca_source": None, "by_setup": {}}
    raw = _git("show", "origin/mcf-data:journal.db", text=False)
    if raw:
        with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as f:
            f.write(raw)
        try:
            c = sqlite3.connect(f.name)
            t = pd.read_sql("SELECT t.strategy, t.entry, t.stop, t.shares, t.pnl, t.pnl_adj FROM trades t JOIN runs r "
                            "ON r.id = t.run_id WHERE r.kind != 'whatif' AND t.date = ? AND t.exit_time IS NOT NULL",
                            c, params=(d,))
            c.close()
        finally:
            os.unlink(f.name)
        if len(t):
            risk = (t.entry - t.stop).abs() * t.shares
            t["r"] = t.pnl_adj.fillna(t.pnl) / risk
            t = t[np.isfinite(t.r) & (risk > 0)]
            out.update(r=round(float(t.r.sum()), 2), trades=int(len(t)), pnl_journal=round(float(t.pnl.sum()), 2),
                       by_setup={k: round(float(v), 2) for k, v in t.groupby("strategy").r.sum().items()})
    try:
        from .reconcile_pl import reconcile

        rc = reconcile(d, "primary", with_fills=False)
        out["pnl_alpaca"], out["alpaca_source"] = rc.get("alpaca_day_pl"), rc.get("source")
    except Exception as e:  # keys / network missing: the journal figure stands, labelled
        out["alpaca_source"] = f"unavailable ({type(e).__name__})"
    return out


# ------------------------------------------------------------------------------------------------------------- report
def summarize(picks: dict, trades: list[dict], signals: pd.DataFrame) -> list[dict]:
    names = _names()
    rows = []
    for s in picks["setups"]:
        x = [t for t in trades if t["strategy"] == s["id"]]
        r = [t["r"] for t in x if t["r"] == t["r"]]
        sg = signals[signals.strategy == s["id"]] if len(signals) else signals
        rows.append({"id": s["id"], "name": names.get(s["id"], s["id"]), "account": s["account"],
                     "account_tag": ACCOUNT_TAG.get(s["account"], s["account"]), "side": s.get("side"),
                     "signals": int(len(sg)), "trades": len(x), "open": sum(1 for t in x if t["open"]),
                     "wins": sum(1 for v in r if v > 0), "r": round(sum(r), 2),
                     "pnl": round(sum(t["pnl"] for t in x), 2)})
    return rows


def _names() -> dict:
    p = ROOT / "docs" / "live" / "setup_names.json"
    try:
        d = json.loads(p.read_text())
        return {k: (v.get("name") if isinstance(v, dict) else v) for k, v in d.items()}
    except Exception:
        return {}


def phase_of(day, now: pd.Timestamp) -> tuple[str, pd.Timestamp | None]:
    """('intraday', cut) during the session, ('closed', None) after it, ('pre-open', None) before 09:31."""
    d = pd.Timestamp(str(day)).date()
    if now.date() < d or (now.date() == d and now.time() < pd.Timestamp("09:31").time()):
        return "pre-open", None
    if now.date() > d or now.time() >= pd.Timestamp("16:00").time():
        return "closed", None
    return "intraday", now.floor("1min")


def build(day, now: pd.Timestamp | None = None, label: str | None = None, picks_file: str | None = None,
          log=print) -> dict:
    """Run the Team for `day` and return the report dict (also the JSON written by `write`)."""
    now = now or pd.Timestamp.now(tz=NY)
    d = str(pd.Timestamp(str(day)).date())
    picks = load_picks(d, picks_file)
    phase, until = phase_of(d, now)
    rep = {"date": d, "label": label,
           "team": "Claude's Team (shadow)", "shadow": LABEL, "phase": phase, "run_at": now.strftime("%Y-%m-%d %H:%M ET"),
           "asof": None, "picks_file": picks["_path"], "picks_date": picks.get("date"),
           "setups": [], "trades": [], "totals": {}, "primary": {}, "method": {}, "disclaimer": DISCLAIMER}
    names = _names()
    rep["setups"] = [{"id": s["id"], "name": names.get(s["id"], s["id"]), "account": s["account"],
                      "account_tag": ACCOUNT_TAG.get(s["account"], s["account"]), "side": s.get("side"),
                      "signals": 0, "trades": 0, "open": 0, "wins": 0, "r": 0.0, "pnl": 0.0} for s in picks["setups"]]
    if phase == "pre-open":
        rep["note"] = f"starts {d[5:]} 09:30 ET"
        return rep
    fetch_branches(sorted({ACCOUNT_BRANCH.get(s["account"], "mcf-data") for s in picks["setups"]} | {"mcf-data"}))
    cfg = team_config(picks, d)
    uni, unote = primary_universe(d)
    syms, snotes = team_symbols(cfg, uni, d)
    exact = sorted({s for st in cfg["strategies"].values() for s in (st.get("symbols") or [])
                    if isinstance(st.get("symbols"), list)})
    priors = get_priors(syms, d, exact, log=log)
    bars = get_bars(syms, d, until, log=log)
    shortable = {str(s): (bool(a), bool(b)) for s, a, b in zip(uni.symbol, uni.shortable, uni.easy_to_borrow)}
    sim = simulate(cfg, d, bars, {s: p for s, p in priors.items() if s in set(syms)}, until, shortable, get_spreads(), log=log)
    last_bar = max((b.index[-1] for b in bars.values() if len(b)), default=None)
    rep["asof"] = None if last_bar is None else (last_bar + pd.Timedelta(minutes=1)).strftime("%Y-%m-%d %H:%M ET")
    rep["trades"] = sorted(sim["trades"], key=lambda t: t["entry_time"] or "")
    rep["setups"] = summarize(picks, rep["trades"], sim["signals"])
    rr = [t["r"] for t in rep["trades"] if t["r"] == t["r"]]
    rep["totals"] = {"trades": len(rep["trades"]), "open": sum(1 for t in rep["trades"] if t["open"]),
                     "wins": sum(1 for v in rr if v > 0), "r": round(sum(rr), 2),
                     "pnl": round(sum(t["pnl"] for t in rep["trades"]), 2),
                     "long_r": round(sum(t["r"] for t in rep["trades"] if t["side"] > 0 and t["r"] == t["r"]), 2),
                     "short_r": round(sum(t["r"] for t in rep["trades"] if t["side"] < 0 and t["r"] == t["r"]), 2)}
    act = actual_primary(d)
    rep["primary"] = act
    if act.get("r") is not None:
        rep["totals"]["vs_primary_r"] = round(rep["totals"]["r"] - act["r"], 2)
    # cross-check only: the home accounts' own live signals / trades of the picked setups that session
    rep["crosscheck"] = crosscheck(picks, d, rep["trades"])
    st = sim["stats"]
    rep["method"] = {"engine": "mcf.replay.harness.run_session (as-live PaperRunner loop), fills=costs, limit_fill=through",
                     "universe": unote, "symbols": snotes.get("symbols"), "earnings_blackout": snotes.get("earnings_blackout"),
                     "bars_symbols": len(bars), "priors": len(priors), "polls": st.get("polls"),
                     "seconds": st.get("seconds"), "rules": "Primary (config/default.yaml): 0.25% risk per trade, "
                     f"{cfg['account'].get('slots')} slots, buying power x{cfg['account'].get('buying_power_multiple')}, "
                     f"-{cfg['account'].get('max_setup_daily_loss_r')}R per-setup daily stop",
                     "costs": cfg.get("costs"), "setup_sources": cfg.get("_team_sources"),
                     "r_definition": "simulated P/L after costs / (|entry - stop| x shares); Primary actual: pnl_adj / risk",
                     "fills": "SIMULATED from 1-minute bars (not broker fills)"}
    return rep


def crosscheck(picks: dict, day: str, team_trades: list[dict]) -> list[dict]:
    """Per picked setup: the home account's live trades / R that session vs the Team's (a different universe and rule set
    can differ; this is a sanity check, never an input)."""
    out = []
    dbs: dict[str, pd.DataFrame | None] = {}
    for s in picks["setups"]:
        br = ACCOUNT_BRANCH.get(s["account"], f"mcf-data-{s['account']}")
        if br not in dbs:
            raw = _git("show", f"origin/{br}:journal.db", text=False)
            t = None
            if raw:
                with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as f:
                    f.write(raw)
                try:
                    c = sqlite3.connect(f.name)
                    t = pd.read_sql("SELECT t.strategy, t.symbol, t.entry, t.stop, t.shares, t.pnl, t.pnl_adj FROM trades t "
                                    "JOIN runs r ON r.id = t.run_id WHERE r.kind != 'whatif' AND t.date = ? "
                                    "AND t.exit_time IS NOT NULL", c, params=(day,))
                    c.close()
                except Exception:
                    t = None
                finally:
                    os.unlink(f.name)
            dbs[br] = t
        t = dbs[br]
        x = t[t.strategy == s["id"]] if t is not None and len(t) else None
        mine = [tt for tt in team_trades if tt["strategy"] == s["id"]]
        home_syms = set(x.symbol) if x is not None else set()
        team_syms = {tt["symbol"] for tt in mine}
        hr = None
        if x is not None and len(x):
            risk = (x.entry - x.stop).abs() * x.shares
            hr = round(float((x.pnl_adj.fillna(x.pnl) / risk)[risk > 0].sum()), 2)
        out.append({"id": s["id"], "home": ACCOUNT_TAG.get(s["account"], s["account"]),
                    "home_trades": 0 if x is None else int(len(x)), "home_r": hr, "team_trades": len(mine),
                    "same_symbols": len(home_syms & team_syms)})
    return out


def write(rep: dict, out_dir: Path = OUT) -> Path:
    p = out_dir / "team" / f"{rep['date']}.json"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(rep, indent=1, default=str))
    return p


def append_scoreboard(rep: dict, path: Path = OUT / "scoreboard.csv") -> Path:
    tot, act = rep.get("totals") or {}, rep.get("primary") or {}
    row = {"date": rep["date"], "run_at": rep["run_at"], "label": rep.get("label") or "", "phase": rep["phase"],
           "asof": rep.get("asof") or "", "setups": len(rep.get("setups") or []), "trades": tot.get("trades", 0),
           "open": tot.get("open", 0), "team_r": tot.get("r", ""), "team_pnl": tot.get("pnl", ""),
           "primary_r": act.get("r", ""), "primary_pnl_journal": act.get("pnl_journal", ""),
           "primary_pnl_alpaca": act.get("pnl_alpaca", ""), "diff_r": tot.get("vs_primary_r", "")}
    new = not path.exists()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=SCOREBOARD_COLS)
        if new:
            w.writeheader()
        w.writerow({k: ("" if v is None else v) for k, v in row.items()})
    return path


def text(rep: dict) -> str:
    tot, act = rep.get("totals") or {}, rep.get("primary") or {}
    if rep["phase"] == "pre-open":
        return f"Claude's Team (shadow) {rep['date']}: {len(rep['setups'])} setups picked; {rep.get('note')}. {DISCLAIMER}"
    pa = act.get("pnl_alpaca")
    lines = [f"Claude's Team (shadow) {rep['date']} {rep['phase']} as of {rep.get('asof')}: {tot.get('r', 0):+.2f}R / "
             f"${tot.get('pnl', 0):+,.2f} after costs ({tot.get('trades', 0)} trades, {tot.get('open', 0)} open) vs Primary "
             f"{'–' if act.get('r') is None else f'{act['r']:+.2f}R'} / Alpaca "
             f"{'–' if pa is None else f'${pa:+,.2f}'}" + (f" [{rep['label']}]" if rep.get("label") else "")]
    for s in rep["setups"]:
        lines.append(f"  {s['r']:+6.2f}R {s['trades']:3d} tr  {s['name']} [{s['account_tag']}]")
    lines.append(f"{LABEL}. {DISCLAIMER}")
    return "\n".join(lines)


